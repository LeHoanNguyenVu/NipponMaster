for ch, cfg in KANJI_BOXES.items():
    page_num = cfg["page"]
    page = doc[page_num - 1]
    pix = page.get_pixmap(dpi=200)
    full_img = Image.frombytes("RGB", [pix.width, pix.height], pix.samples)
    W, H = full_img.size

    for order, (x1_pct, y1_pct, x2_pct, y2_pct) in cfg["boxes"].items():
        left = int(x1_pct * W)
        top = int(y1_pct * H)
        right = int(x2_pct * W)
        bottom = int(y2_pct * H)
        
        cropped = full_img.crop((left, top, right, bottom))
        out_filename = f"chap{ch}_kanji_{order}.webp"
        out_path = os.path.join(OUTPUT_DIR, out_filename)
        cropped.save(out_path, "WEBP", quality=92, method=6)

print("Updated all illustrations with enhanced bounding boxes!")
