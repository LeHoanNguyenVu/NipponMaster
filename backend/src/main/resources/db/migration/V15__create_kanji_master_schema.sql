-- 1. Kanji Chapters Table (15 Chương chuẩn giáo trình Kanji Master N5)
CREATE TABLE IF NOT EXISTS kanji_chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP,
    chapter_number INTEGER NOT NULL,
    jlpt_level VARCHAR(10) NOT NULL DEFAULT 'N5',
    title_ja VARCHAR(100) NOT NULL,
    title_vi VARCHAR(200) NOT NULL,
    title_en VARCHAR(200),
    kanji_count INTEGER NOT NULL DEFAULT 0,
    display_order INTEGER NOT NULL,
    illustration_url VARCHAR(500),
    description TEXT,
    CONSTRAINT uq_kanji_chapters_level_num UNIQUE (jlpt_level, chapter_number)
);

-- 2. Thêm trường chapter_id và chapter_order vào bảng kanjis
ALTER TABLE kanjis ADD COLUMN IF NOT EXISTS chapter_id BIGINT REFERENCES kanji_chapters(id) ON DELETE SET NULL;
ALTER TABLE kanjis ADD COLUMN IF NOT EXISTS chapter_order INTEGER;
CREATE INDEX IF NOT EXISTS idx_kanjis_chapter ON kanjis(chapter_id);
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_kanjis_character'
    ) THEN
        ALTER TABLE kanjis ADD CONSTRAINT uq_kanjis_character UNIQUE (character);
    END IF;
END $$;


-- 3. Từ vựng ứng dụng theo từng chương (Kanji Chapter Vocab)
CREATE TABLE IF NOT EXISTS kanji_chapter_vocab (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    chapter_id BIGINT NOT NULL REFERENCES kanji_chapters(id) ON DELETE CASCADE,
    word VARCHAR(100) NOT NULL,
    reading VARCHAR(100) NOT NULL,
    romaji VARCHAR(100),
    meaning_vi VARCHAR(255) NOT NULL,
    meaning_en VARCHAR(255),
    display_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_kanji_vocab_chapter ON kanji_chapter_vocab(chapter_id);

-- 4. Ngân hàng câu đọc (よみましょう) và câu viết (かきましょう)
CREATE TABLE IF NOT EXISTS kanji_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    chapter_id BIGINT NOT NULL REFERENCES kanji_chapters(id) ON DELETE CASCADE,
    exercise_type VARCHAR(20) NOT NULL, -- 'READING' hoặc 'WRITING'
    question_text TEXT NOT NULL,
    target_word VARCHAR(100) NOT NULL,
    correct_answer VARCHAR(100) NOT NULL,
    options_json TEXT, -- Mảng lựa chọn trắc nghiệm JSON
    explanation TEXT,
    display_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_kanji_exercises_chapter ON kanji_exercises(chapter_id);

-- 5. Minigame câu đố giải trí (Phép cộng chữ, giải đố tranh, đếm đồ vật...)
CREATE TABLE IF NOT EXISTS kanji_minigames (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    chapter_id BIGINT NOT NULL REFERENCES kanji_chapters(id) ON DELETE CASCADE,
    game_type VARCHAR(50) NOT NULL, -- 'ORDERING', 'COUNTING', 'CALCULATION', 'POSTCARD_FILL', 'KANJI_ADDITION', 'PICTURE_MATCH'
    title VARCHAR(200) NOT NULL,
    instruction TEXT NOT NULL,
    image_url VARCHAR(500),
    game_data_json TEXT NOT NULL, -- Cấu hình dữ liệu trò chơi JSON
    display_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_kanji_minigames_chapter ON kanji_minigames(chapter_id);

-- 6. Đề thi tổng hợp theo chặng (Achievement Tests)
CREATE TABLE IF NOT EXISTS kanji_achievement_tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    stage INTEGER NOT NULL, -- 1: Chặng 1-5, 2: Chặng 6-10, 3: Chặng 11-15
    title VARCHAR(200) NOT NULL,
    description TEXT,
    pass_percentage INTEGER NOT NULL DEFAULT 85,
    test_data_json TEXT NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0
);

-- 7. Tiến độ học thực tế và mở khóa theo tài khoản học viên (User Kanji Progress)
CREATE TABLE IF NOT EXISTS user_kanji_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    chapter_id BIGINT NOT NULL REFERENCES kanji_chapters(id) ON DELETE CASCADE,
    is_unlocked BOOLEAN NOT NULL DEFAULT FALSE,
    highest_score INTEGER NOT NULL DEFAULT 0,
    is_passed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMP,
    CONSTRAINT uq_user_kanji_progress UNIQUE (user_id, chapter_id)
);
CREATE INDEX IF NOT EXISTS idx_user_kanji_prog_user ON user_kanji_progress(user_id);
CREATE INDEX IF NOT EXISTS idx_user_kanji_prog_chap ON user_kanji_progress(chapter_id);

